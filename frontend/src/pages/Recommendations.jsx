import { useState } from "react";
import { Link } from "react-router-dom";
import { Calculator, Sparkles } from "lucide-react";
import FilterBar from "../components/FilterBar";
import { EmptyState, ErrorBox, Loading } from "../components/States";
import useFetch from "../hooks/useFetch";
import { api } from "../services/api";
import { defaultRange, fmt } from "../utils/format";

export default function Recommendations() {
  const [f, setF] = useState(defaultRange());
  const { data, loading, error, reload } = useFetch(() => api.recommendations(f), [f.start, f.end]);
  return (
    <div className="page">
      <div className="page-head"><div><h1>Recommendations</h1><p>Savings are calculated with the emission factors. AI only adds a short explanation.</p></div></div>
      <FilterBar value={f} onChange={setF} showCategory={false} />
      {loading && <Loading text="Building recommendations..." />}
      {error && <ErrorBox message={error} onRetry={reload} />}
      {data && !data.sufficient && <EmptyState title="Not enough data yet" text={data.message}><Link className="btn" to="/add">Add activity</Link></EmptyState>}
      {data?.sufficient && (
        <>
          <div className={`banner ${data.source === "rule-based" ? "" : "ok"}`} style={{ marginBottom: 14 }}>
            {data.source === "gemini+rules" ? "AI explanations are on. Savings figures below are calculated, not generated by AI." : `Rule-based recommendations. ${data.ai_status === "not configured" ? "Add a Gemini API key on the backend to enable AI explanations." : data.ai_status}`}
          </div>
          <div className="grid">
            {data.recommendations.map((r) => (
              <article className="card" key={r.id}>
                <div className="row" style={{ justifyContent: "space-between" }}>
                  <h2 style={{ margin: 0 }}>{r.title}</h2>
                  <div className="row"><span className={`badge ${r.priority === "High" ? "bad" : ""}`}>{r.priority} priority</span><span className="badge">{r.difficulty}</span></div>
                </div>
                <p><strong>Why:</strong> {r.reason}</p>
                <p><strong>Action:</strong> {r.action}</p>
                <div className="card soft">
                  <div className="row"><Calculator size={16} /><strong>Calculated saving: {fmt(r.reduction_kg)} kg CO2e</strong><span className="muted small">over {r.period}</span></div>
                  {r.annual_reduction_kg != null && <div className="small muted">About {fmt(r.annual_reduction_kg)} kg CO2e per year if this period is typical.</div>}
                  <div className="small muted">{r.formula}</div>
                  <ul className="lines small">{r.assumptions.map((a, i) => <li key={i}>{a}</li>)}</ul>
                </div>
                {data.ai_explanations[r.id] && <p className="small" style={{ marginBottom: 0 }}><Sparkles size={14} /> <strong>AI explanation:</strong> {data.ai_explanations[r.id]}</p>}
              </article>
            ))}
          </div>
        </>
      )}
    </div>
  );
}
